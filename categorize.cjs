function categorize(name) {
    const lower = name.toLowerCase();
    for (const rule of rules) {
        for (const kw of rule.kws) {
            if (lower.includes(kw.toLowerCase())) return rule;
        }
    }
    return null;
}

const results = rows.map(r => {
    const cat = categorize(r.name);
    return { ...r, category_id: cat ? cat.id : 17, category_name: cat ? cat.name : 'عدد وأدوات يدوية' };
});

const dist = {};
results.forEach(r => { dist[r.category_name] = (dist[r.category_name] || 0) + 1; });

console.log('\n=== DISTRIBUTION ===');
